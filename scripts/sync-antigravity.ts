// Makes this repo usable from Google Antigravity as well as Claude Code.
//
//   node scripts/sync-antigravity.ts           write the Antigravity files
//   node scripts/sync-antigravity.ts --check   change nothing; exit 1 if they are out of date (used by CI)
//
// Claude Code reads  CLAUDE.md, .claude/skills/<name>/SKILL.md, .claude/agents/<name>.md.
// Antigravity reads  AGENTS.md, .agents/skills/<name>/SKILL.md, .agents/agents/<name>.md  (and not the .claude/ files).
// The .claude/ files and CLAUDE.md stay the single source of truth. Everything below is generated from them,
// so edit those, then run `npm run sync:antigravity` and commit the result.
//
// What the conversion does:
//   skills   keep only `name` and `description` (the only fields Antigravity documents), quote the description,
//            point .claude/ paths at .agents/, and mark hidden internal steps as internal in the description
//   agents   keep `name` and `description`, add `mainAgent: false` and `subagent: true`. `tools` is left out on
//            purpose: Antigravity warns that a wrong tool name can hang a sub-agent, so the "review only" rule of
//            monavi-brand-guardian is kept in its text instead
//   AGENTS.md CLAUDE.md plus a short note on how Claude Code wording maps to Antigravity
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { ROOT } from './lib/brand.ts';

const args = process.argv.slice(2);
if (args.includes('--help') || args.includes('-h')) {
  console.log('Usage: npm run sync:antigravity -- [--check]\n\n  (no flags)   write .agents/ and AGENTS.md from .claude/ and CLAUDE.md\n  --check      change nothing; exit 1 if they are out of date');
  process.exit(0);
}
const unknown = args.filter(a => a !== '--check');
if (unknown.length) { console.error(`Unknown arguments: ${unknown.join(' ')}`); process.exit(1); }
const check = args.includes('--check');

const MARK = 'Generated by `npm run sync:antigravity`';
const lf = (s: string): string => s.replace(/\r\n/g, '\n');
const toAgents = (s: string): string => s.replace(/\.claude\/skills\//g, '.agents/skills/').replace(/\.claude\/agents\//g, '.agents/agents/');

interface Doc { meta: Record<string, string>; body: string }
function parse(text: string, file: string): Doc {
  const t = lf(text);
  const m = t.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!m) throw new Error(`${file}: missing frontmatter`);
  const meta: Record<string, string> = {};
  for (const line of m[1]!.split('\n')) {
    const kv = line.match(/^([A-Za-z-]+):\s*(.*)$/);
    if (kv) meta[kv[1]!] = kv[2]!.replace(/^"(.*)"$/, '$1');
  }
  if (!meta.name || !meta.description) throw new Error(`${file}: needs name and description`);
  return { meta, body: m[2]! };
}
const q = (s: string): string => JSON.stringify(s);   // a quoted string is always valid YAML

const expected = new Map<string, string>();           // repo-relative path -> content

// ---- skills
const SKILLS = path.join(ROOT, '.claude', 'skills');
const skillNames: string[] = [];
for (const dir of readdirSync(SKILLS, { withFileTypes: true }).filter(d => d.isDirectory()).map(d => d.name).sort()) {
  const src = path.join(SKILLS, dir, 'SKILL.md');
  if (!existsSync(src)) continue;
  const { meta, body } = parse(readFileSync(src, 'utf8'), src);
  if (meta.name !== dir) throw new Error(`${src}: name "${meta.name}" must match its folder "${dir}"`);
  skillNames.push(dir);
  const internal = meta['user-invocable'] === 'false';
  const description = internal ? `Internal step, normally run by the other skills (not by the user). ${meta.description}` : meta.description;
  expected.set(`.agents/skills/${dir}/SKILL.md`,
    `---\nname: ${dir}\ndescription: ${q(description)}\n---\n<!-- ${MARK} from .claude/skills/${dir}/SKILL.md. Edit that file, not this one. -->\n${toAgents(body)}`);
}

// ---- agents
const AGENTS = path.join(ROOT, '.claude', 'agents');
const agentNames: string[] = [];
for (const f of readdirSync(AGENTS).filter(x => x.endsWith('.md')).sort()) {
  const { meta, body } = parse(readFileSync(path.join(AGENTS, f), 'utf8'), f);
  const n = path.basename(f, '.md');
  if (meta.name !== n) throw new Error(`${f}: name "${meta.name}" must match the file name`);
  agentNames.push(n);
  expected.set(`.agents/agents/${n}.md`,
    `---\nname: ${n}\ndescription: ${q(meta.description)}\nmainAgent: false\nsubagent: true\n---\n<!-- ${MARK} from .claude/agents/${n}.md. Edit that file, not this one. -->\n${toAgents(body)}`);
}

// ---- AGENTS.md
const NOTES = `

## Using this repo from Antigravity

This file is generated from \`CLAUDE.md\` for Google Antigravity. The skills are in \`.agents/skills/\` and the agents in \`.agents/agents/\`. Everything above applies as written, with this wording mapped:

| The instructions say | In Antigravity |
|---|---|
| "Claude", "Claude Code" | You, the agent in Antigravity |
| \`/create-social-content\` and the other \`/commands\` | The same skill names: type \`/<skill-name>\` in the message box, then the details as normal text. Skills also start on their own when a request matches their description |
| "Read" a file or an image | Open it with your file viewer (for example \`view_file\`). Always look at every rendered image before saying it is fine |
| "Write" or "Edit" a file | Create or edit the file with your file tools |
| "Run \`npm run …\`", "\`git …\`", "\`gh …\`" | Run it in the terminal (for example \`run_command\`), and do it yourself. The user never runs these |
| "Run the \`monavi-brand-guardian\`, \`monavi-content-strategist\` or \`caption-writer\` agent" | Invoke that sub-agent from \`.agents/agents/\`. If sub-agents are not available, read its file and carry out its steps yourself as a separate, careful pass |
| Skills marked "hidden" or "internal" | They show up in the slash menu here. Users only need the ones listed under "user commands" |

The sub-agents here have no tool list, so "review only" and "plans only" are rules of their text: \`monavi-brand-guardian\` and \`monavi-content-strategist\` must never edit, render, or open PRs.

Edit \`CLAUDE.md\` and \`.claude/\`, never this file or \`.agents/\`. After a change, run \`npm run sync:antigravity\` and commit the result. CI fails when they are out of date.
`;
const claude = lf(readFileSync(path.join(ROOT, 'CLAUDE.md'), 'utf8')).replace(/\n+$/, '');
const agentsMd = `<!-- ${MARK} from CLAUDE.md. Edit CLAUDE.md, not this file. -->\n${toAgents(claude)}${NOTES}`;
if (Buffer.byteLength(agentsMd) > 24_000) throw new Error('AGENTS.md is over Antigravity\'s 24 KB per-file limit. Trim CLAUDE.md.');
expected.set('AGENTS.md', agentsMd);

// ---- compare / write
const abs = (rel: string) => path.join(ROOT, ...rel.split('/'));
const stale: string[] = [];
for (const [rel, content] of expected) {
  const f = abs(rel);
  if (!existsSync(f) || lf(readFileSync(f, 'utf8')) !== content) stale.push(rel);
}
// Generated files whose source is gone (only ones carrying our marker; anyone else's files are left alone).
const orphans: string[] = [];
for (const [dir, names, file] of [['.agents/skills', skillNames, 'SKILL.md'], ['.agents/agents', agentNames, '']] as const) {
  if (!existsSync(abs(dir))) continue;
  for (const e of readdirSync(abs(dir), { withFileTypes: true })) {
    const name = file ? e.name : e.name.replace(/\.md$/, '');
    if (names.includes(name)) continue;
    const f = file ? path.join(abs(dir), e.name, file) : path.join(abs(dir), e.name);
    if (existsSync(f) && readFileSync(f, 'utf8').includes(MARK)) orphans.push(path.relative(ROOT, file ? path.dirname(f) : f).split(path.sep).join('/'));
  }
}

if (check) {
  if (stale.length || orphans.length) {
    for (const s of stale) console.error(`out of date: ${s}`);
    for (const o of orphans) console.error(`no longer has a source: ${o}`);
    console.error('\nThe Antigravity files are out of date. Run `npm run sync:antigravity` and commit the result.');
    process.exit(1);
  }
  console.log(`Antigravity files are up to date (${skillNames.length} skills, ${agentNames.length} agents, AGENTS.md).`);
  process.exit(0);
}

for (const rel of stale) {
  mkdirSync(path.dirname(abs(rel)), { recursive: true });
  writeFileSync(abs(rel), expected.get(rel)!);
  console.log(`wrote  ${rel}`);
}
for (const o of orphans) { rmSync(abs(o), { recursive: true, force: true }); console.log(`removed ${o}`); }
console.log(`${stale.length || orphans.length ? '' : 'Already up to date. '}${skillNames.length} skills, ${agentNames.length} agents, AGENTS.md.`);
